func drawTachyon(grid [][]rune, row, col int, splits *int, visited map[[2]int]bool) {
	if row >= len(grid) || col < 0 || col >= len(grid[0]) {
		return
	}
	if grid[row][col] == '^' {
		key := [2]int{row, col}
		if !visited[key] {
			visited[key] = true
			*splits++
		}
		drawTachyon(grid, row+1, col-1, splits, visited)
		drawTachyon(grid, row+1, col+1, splits, visited)
		return
	}
	if grid[row][col] == '.' {
		drawTachyon(grid, row+1, col, splits, visited)
	}
}

type Beam struct {
	row, col int
}

func countSplits(lines []string) int {
	startCol := strings.Index(lines[0], "S")
	queue := []Beam{{row: 1, col: startCol}}
	visited := make(map[[2]int]bool)
	splitsSeen := make(map[[2]int]bool)

	totalSplits := 0

	for len(queue) > 0 {
		beam := queue[0]
		queue = queue[1:]

		row, col := beam.row, beam.col

		if row >= len(lines) || col < 0 || col >= len(lines[0]) {
			continue
		}

		key := [2]int{row, col}
		if visited[key] {
			continue
		}
		visited[key] = true

		if lines[row][col] == '^' {
			if !splitsSeen[key] {
				splitsSeen[key] = true
				totalSplits++
			}
			queue = append(queue, Beam{row + 1, col - 1})
			queue = append(queue, Beam{row + 1, col + 1})
			continue
		}

		if lines[row][col] == '.' {
			queue = append(queue, Beam{row + 1, col})
		}
	}

	return totalSplits
}

func dfsWithCache(lines []string, row, col int, cache map[[2]int]int) int {
	if row >= len(lines) || col < 0 || col >= len(lines[0]) {
		return 1
	}
	key := [2]int{row, col}
	if val, ok := cache[key]; ok {
		return val
	}
	result := 0

	if lines[row][col] == '^' {
		left := dfsWithCache(lines, row+1, col-1, cache)
		right := dfsWithCache(lines, row+1, col+1, cache)
		result = left + right
	} else if lines[row][col] == '.' {
		result = dfsWithCache(lines, row+1, col, cache)
	} else {
		result = 1
	}

	cache[key] = result
	return result
}

